#!/usr/bin/env python3
"""
inspect_packets.py
Extracts human-readable Wire View packet timelines and event statistics
from MRC_TRACE_FILE CSV logs generated by htsim_uec.
"""

import argparse
import csv
from collections import Counter
from pathlib import Path


def summarize_trace(trace_csv: Path, out_md: Path, max_events: int = 40) -> dict:
    counts = Counter()
    interesting_rows = []
    unique_evs = set()
    syn_seen = False
    eom_seen = False

    with trace_csv.open("r", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            ev_name = row["event"]
            counts[ev_name] += 1
            unique_evs.add(row["ev"])
            if row["syn"] == "1":
                syn_seen = True
            if row["eom"] == "1":
                eom_seen = True

            # Capture key milestone events for the Wire View table
            is_key = (
                ev_name in {"SW_TRIM", "SW_DROPDTT", "SW_BTS", "SW_SKIP_SHORT_TRIM",
                            "RX_TRIM", "TX_NACK", "RX_NACK", "TX_RTX", "TX_PROBE", "RX_PULL"}
                or row["syn"] == "1"
                or row["eom"] == "1"
                or (ev_name == "SW_ECN" and counts["SW_ECN"] <= 5)
                or (ev_name == "RX_ACK" and counts["RX_ACK"] <= 5)
            )
            if is_key and len(interesting_rows) < max_events:
                interesting_rows.append(row)

    lines = [
        f"# Wire View Report: `{trace_csv.name}`",
        "",
        "## 1. Event Counters",
        "| Event | Count |",
        "| :--- | ---: |",
    ]
    for k, v in sorted(counts.items()):
        lines.append(f"| `{k}` | {v} |")

    lines.extend([
        "",
        f"- **Unique Entropy Values (EVs) observed**: `{len(unique_evs)}`",
        f"- **0-RTT SYN observed**: `{syn_seen}` | **EOM observed**: `{eom_seen}`",
        "",
        "## 2. Key Packet Timeline (Wire View)",
        "| Time (ns) | Event | Flow | PSN | CummACK | EV | DSCP | ECN | Flags | Size (B) | Extra |",
        "| ---: | :--- | ---: | ---: | ---: | :--- | :--- | ---: | :--- | ---: | :--- |",
    ])
    for r in interesting_rows:
        flags = []
        if r["syn"] == "1": flags.append("SYN")
        if r["eom"] == "1": flags.append("EOM")
        if r["trimmed"] == "1": flags.append("TRIM")
        if r["rtx"] == "1": flags.append("RTX")
        if r["probe"] == "1": flags.append("PROBE")
        if r["bts"] == "1": flags.append("BTS")
        flag_str = ",".join(flags) if flags else "-"
        lines.append(
            f"| {r['ts_ns']} | `{r['event']}` | {r['flow_id']} | {r['psn']} | "
            f"{r['cumm_ack']} | `{r['ev']}` | `{r['dscp']}` | {r['ecn']} | "
            f"{flag_str} | {r['size']} | {r['extra'] or '-'} |"
        )

    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text("\n".join(lines) + "\n")
    return {
        "counts": dict(counts),
        "unique_evs": len(unique_evs),
        "syn_seen": syn_seen,
        "eom_seen": eom_seen,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("trace_csv", type=Path)
    ap.add_argument("-o", "--output", type=Path, required=True)
    ap.add_argument("--max-events", type=int, default=40)
    args = ap.parse_args()
    summarize_trace(args.trace_csv, args.output, args.max_events)


if __name__ == "__main__":
    main()
